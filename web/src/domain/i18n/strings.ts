export type Locale = 'it' | 'en'

const dictionaries: Record<Locale, Record<StringKey, string>> = { it, en }

let locale: Locale = 'it'

export const getLocale = (): Locale => locale
/** The app speaks Italian; tests that compare with the Android app switch to English. */
export function setLocale(next: Locale): void {
  locale = next
}

/** A string by key, with {name} placeholders filled from vars. */
export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

/** The singular or plural form of a noun for a count: "1 rep", "3 reps"; "1 ripetizione", "3 ripetizioni". */
export function count(n: number, noun: 'rep' | 'set' | 'exercise'): string {
  return `${n} ${t(n === 1 ? (`${noun}_one` as StringKey) : (`${noun}_other` as StringKey))}`
}

/** A phrase whose form depends on a count, such as "(2 remaining)" and "(ne manca 1)". */
export function tn(base: 'remaining', n: number): string {
  return t(n === 1 ? (`${base}_one` as StringKey) : (`${base}_other` as StringKey), { n })
}
